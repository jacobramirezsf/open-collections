import { chromium, devices } from 'playwright'
const browser = await chromium.launch()
const page = await browser.newPage({ ...devices['iPhone 13'] })
page.on('pageerror', (e) => console.log('PAGEERROR:', e.message))
await page.goto('http://localhost:5180/', { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(1200)
await page.evaluate(() => localStorage.setItem('open-collections:intro-seen:v1', '1'))
await page.reload({ waitUntil: 'domcontentloaded' })
await page.fill('input[type="search"], .searchbar input', 'tulip painting')
await page.keyboard.press('Enter')
await page.waitForSelector('.card img.loaded', { timeout: 30000 })
await page.click('.card >> nth=0')
await page.waitForSelector('.viewer', { timeout: 15000 })
await page.click('button:has-text("Edit")')
await page.waitForTimeout(2500)
const before = await page.evaluate(() => { const c = document.querySelector('.editor .stage canvas'); return `${c.width}x${c.height}` })
console.log('1. source before crop:', before)
await page.click('button.mobile-only:has-text("Crop")')
await page.waitForSelector('.crop-tool', { timeout: 8000 })
await page.waitForTimeout(600)
// drag a small region in the middle of the image
// drag the SE handle inward to make a small crop
const h = await page.locator('.crop-h.se').boundingBox()
const box0 = await page.locator('.crop-box').boundingBox()
await page.mouse.move(h.x + h.width / 2, h.y + h.height / 2)
await page.mouse.down()
await page.mouse.move(box0.x + box0.width * 0.4, box0.y + box0.height * 0.35, { steps: 12 })
await page.mouse.up()
await page.waitForTimeout(400)
console.log('2. crop size readout:', (await page.locator('.crop-dock .faint').last().textContent()).slice(0, 26))
await page.screenshot({ path: 'data/shots/crop-tool.png' })
await page.click('.vtop button:has-text("Crop")')
await page.waitForTimeout(2500)
const after = await page.evaluate(() => { const c = document.querySelector('.editor .stage canvas'); return `${c.width}x${c.height}` })
console.log('3. canvas after crop:', after, after !== before ? 'PASS (resized to the crop)' : 'FAIL')
await page.screenshot({ path: 'data/shots/crop-applied.png' })
// effects still work on the crop
await page.getByRole('button', { name: 'Halftone', exact: true }).click()
await page.waitForTimeout(2500)
console.log('4. effect on the crop:', await page.evaluate(() => { const c = document.querySelector('.editor .stage canvas'); return `${c.width}x${c.height}` }))
// and background removal
await page.click('button.mobile-only:has-text("Cutout")')
const done = await page.waitForSelector('button:has-text("Background removed"), .mobile-only.active', { timeout: 120000 }).then(() => 'ran').catch(() => 'timeout')
console.log('5. cutout on the crop:', done)
await page.screenshot({ path: 'data/shots/crop-effects.png' })
await browser.close()
