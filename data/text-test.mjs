import { chromium, devices } from 'playwright'
const browser = await chromium.launch()
const page = await browser.newPage({ ...devices['iPhone 13'] })
page.on('pageerror', (e) => console.log('PAGEERROR:', e.message))
await page.goto('http://localhost:5180/', { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(1200)
await page.evaluate(() => localStorage.setItem('open-collections:intro-seen:v1', '1'))
await page.reload({ waitUntil: 'domcontentloaded' })
await page.waitForTimeout(1200)
await page.click('button:has-text("Canvas")')
await page.waitForSelector('.canvas-studio')
await page.click('button:has-text("+ Add text")')
await page.waitForSelector('.text-pop', { timeout: 6000 })
await page.fill('.text-pop textarea', 'OPEN\nCOLLECTIONS')
await page.selectOption('.text-pop select >> nth=0', { label: 'Anton' })
await page.waitForTimeout(400)
await page.click('.text-pop button:has-text("Add to canvas")')
await page.waitForTimeout(3000)
console.log('1. text piece added:', await page.locator('.piece').count())
const dims = await page.locator('.piece img').first().evaluate((el) => ({ w: el.naturalWidth, h: el.naturalHeight }))
console.log('   rendered at', dims, dims.w > 200 ? 'PASS' : 'FAIL')
await page.screenshot({ path: 'data/shots/text-piece.png' })
// edit it and apply an effect
await page.click('.piece')
await page.waitForTimeout(400)
await page.click('button:has-text("Edit text")')
await page.waitForSelector('.text-pop')
await page.selectOption('.text-pop select >> nth=-1', 'halftone')
await page.click('.text-pop button:has-text("Update")')
await page.waitForTimeout(3500)
const dims2 = await page.locator('.piece img').first().evaluate((el) => ({ w: el.naturalWidth, h: el.naturalHeight }))
console.log('2. effect applied to text, still a piece:', await page.locator('.piece').count(), dims2)
await page.screenshot({ path: 'data/shots/text-effect.png' })
await browser.close()
