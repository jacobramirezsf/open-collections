import { chromium } from 'playwright'
const browser = await chromium.launch()
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } })
const page = await ctx.newPage()
page.on('pageerror', (e) => console.log('PAGEERROR:', e.message))
page.on('console', (m) => { if (m.type() === 'error' && !/favicon|404/.test(m.text())) console.log('CONSOLE:', m.text().slice(0, 160)) })
await page.route('**/api/vectorize', async (route) => {
  await route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ svg: '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100"><rect width="100" height="100" fill="#eee"/><circle cx="50" cy="50" r="30" fill="#c33"/></svg>', model: 'arrow-2', sandbox: false }) })
})
await page.goto('http://localhost:5180/#/studio', { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(1000)
console.log('1. hub:', await page.title(), '| tiles:', await page.$$eval('.studio-tile strong', (b) => b.map((x) => x.textContent).join(', ')), '| top buttons:', await page.$$eval('.studio-top .btn', (b) => b.map((x) => x.textContent.trim()).join(', ')))
await page.screenshot({ path: 'data/shots/studio-hub.png' })
// a test image: big letters plus colour shapes, the kind of thing letterpress and riso are for
const buf = await page.evaluate(async () => {
  const c = document.createElement('canvas'); c.width = 1200; c.height = 800
  const x = c.getContext('2d')
  x.fillStyle = '#fff'; x.fillRect(0, 0, 1200, 800)
  const g = x.createLinearGradient(0, 0, 1200, 0); g.addColorStop(0, '#2b6cb0'); g.addColorStop(1, '#e53e3e')
  x.fillStyle = g; x.beginPath(); x.arc(900, 520, 220, 0, Math.PI * 2); x.fill()
  x.fillStyle = '#f6c343'; x.fillRect(120, 470, 380, 220)
  x.fillStyle = '#111'; x.font = 'bold 260px Georgia'; x.fillText('Ag', 90, 360)
  x.font = 'bold 60px Georgia'; x.fillText('LETTERPRESS', 560, 200)
  return c.toDataURL('image/png').split(',')[1]
})
// Editor tile
await page.setInputFiles('.studio-tile:nth-child(1) input[type=file]', { name: 'type-test.png', mimeType: 'image/png', buffer: Buffer.from(buf, 'base64') })
await page.waitForSelector('.editor', { timeout: 15000 })
await page.waitForTimeout(1500)
console.log('2. editor opened from the tile:', location => 1, '| hash:', await page.evaluate(() => location.hash), '| Save to Edits present:', await page.locator('.export-actions button:has-text("Save to Edits")').count())
const chips = await page.$$eval('.editor .chips button', (b) => b.map((x) => x.textContent.trim()))
console.log('3. chips include Riso v3 / Letterpress:', chips.includes('Riso v3'), chips.includes('Letterpress'), '| older riso chips intact:', chips.filter((c) => /^Riso/.test(c)).join(', '))
const drawn = async () => page.evaluate(() => { const c = document.querySelector('.editor .stage canvas'); const x = c.getContext('2d'); const d = x.getImageData(0, 0, c.width, c.height).data; let n = 0; for (let i = 3; i < d.length; i += 4 * 97) if (d[i] > 0) n++; return { w: c.width, h: c.height, sampled: n } })
await page.getByRole('button', { name: 'Riso v3', exact: true }).click()
await page.waitForTimeout(4000)
console.log('4. Riso v3 renders:', JSON.stringify(await drawn()), '| controls:', await page.$$eval('.controls-wrap .label', (l) => l.map((x) => x.textContent.split('·')[0].trim()).join(', ')), '| presets shown:', await page.locator('button:has-text("Riso"):not(.chips button)').count() > 0)
await page.screenshot({ path: 'data/shots/riso-v3.png' })
await page.getByRole('button', { name: 'Riso v3', exact: true }).click() // remove
await page.getByRole('button', { name: 'Letterpress', exact: true }).click()
await page.waitForTimeout(4000)
console.log('5. Letterpress renders:', JSON.stringify(await drawn()), '| controls:', await page.$$eval('.controls-wrap .label', (l) => l.map((x) => x.textContent.split('·')[0].trim()).join(', ')))
await page.screenshot({ path: 'data/shots/letterpress.png' })
// save the upload's edit
await page.click('.export-actions button:has-text("Save to Edits")')
await page.waitForTimeout(3500)
const boards = await page.evaluate(() => JSON.parse(localStorage.getItem('open-collections:boards:v1') || '[]'))
const edits = boards.find((b) => b.id === 'edits')
console.log('6. saved to Edits (local):', edits ? edits.items.map((i) => `${i.id} → ${String(i.thumbnailUrl).slice(0, 16)}`).join(' ; ') : 'NO EDITS BOARD', '| toast:', await page.locator('.toast').textContent().catch(() => '-'))
// back to the hub: recent saves
await page.click('.editor button:has-text("Back")')
await page.waitForSelector('.dropzone', { timeout: 5000 })
await page.click('button:has-text("Back to the studio")')
await page.waitForSelector('.studio-tiles', { timeout: 5000 })
await page.waitForTimeout(800)
console.log('7. hub again:', await page.evaluate(() => location.hash), '| recent saves:', await page.locator('.studio-strip figure').count(), '| thumb loads:', await page.evaluate(() => { const i = document.querySelector('.studio-strip img'); return i ? (i.naturalWidth > 0 ? 'yes' : 'no ' + i.src.slice(0, 20)) : 'none' }))
await page.screenshot({ path: 'data/shots/studio-hub-recent.png' })
// Vectorize tile → save to board
await page.setInputFiles('.studio-tile:nth-child(2) input[type=file]', { name: 'logo.png', mimeType: 'image/png', buffer: Buffer.from(buf, 'base64') })
await page.waitForSelector('.vt-compare', { timeout: 10000 })
console.log('8. vectorize opened from the tile:', await page.evaluate(() => location.hash), '| image already loaded:', await page.locator('.vt-pane figcaption').first().textContent())
await page.click('.vt-actions button.primary:has-text("Vectorize")')
await page.waitForSelector('img[alt="Vectorized"]', { timeout: 30000 })
await page.click('.vt-actions button:has-text("Save to board")')
await page.waitForSelector('.pop', { timeout: 5000 })
const popBtns = await page.$$eval('.pop button', (b) => b.map((x) => x.textContent.trim()))
console.log('9. save popover boards:', popBtns.slice(0, 5).join(' | '))
await page.click('.pop button:has-text("Edits")')
await page.waitForTimeout(1500)
const boards2 = await page.evaluate(() => JSON.parse(localStorage.getItem('open-collections:boards:v1') || '[]'))
const edits2 = boards2.find((b) => b.id === 'edits')
console.log('10. vector saved:', edits2.items.filter((i) => i.objectType === 'Vector').map((i) => `${i.title} · ${i.medium} → ${String(i.thumbnailUrl).slice(0, 11)}`).join(' ; '), '| toast:', await page.locator('.toast').textContent().catch(() => '-'))
// account + boards panels open from the hub
await page.click('button:has-text("Back to the studio")')
await page.waitForSelector('.studio-tiles')
await page.click('.studio-top button:has-text("Sign in")')
console.log('11. sign-in panel:', await page.locator('.panel, .side, [role=dialog]').count() > 0 ? 'open' : await page.locator('input[placeholder*="sername"], input[name=username]').count())
await page.keyboard.press('Escape')
await page.click('.studio-top button:has-text("Boards")')
await page.waitForTimeout(300)
console.log('12. boards panel lists Edits:', await page.locator('text=Edits').count() > 0)
await page.keyboard.press('Escape')
// legacy hashes land inside the studio
await page.goto('http://localhost:5180/#/vectorize', { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(600)
console.log('13. #/vectorize → vectorize inside studio:', await page.locator('.vt').count(), '| #/editor:', await (async () => { await page.goto('http://localhost:5180/#/editor'); await page.waitForTimeout(600); return page.locator('.uploader .dropzone').count() })())
// mobile hub
const m = await ctx.newPage(); await m.setViewportSize({ width: 390, height: 844 })
await m.goto('http://localhost:5180/#/studio', { waitUntil: 'domcontentloaded' }); await m.waitForTimeout(800)
console.log('14. mobile hub overflow:', await m.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), '| tiles stacked:', await m.$$eval('.studio-tile', (t) => t.map((x) => Math.round(x.getBoundingClientRect().width)).join(',')))
await m.screenshot({ path: 'data/shots/studio-hub-mobile.png', fullPage: true })
await browser.close()
