import { chromium, devices } from 'playwright'
const BASE = process.argv[2] || 'http://localhost:5180'
const browser = await chromium.launch()
const ctx = await browser.newContext({ ...devices['iPhone 13'] })
const page = await ctx.newPage()
const errs = []
page.on('pageerror', (e) => errs.push(e.message))
page.on('console', (m) => { if (m.type() === 'error') errs.push('console: ' + m.text().slice(0, 120)) })
await page.goto(BASE + '/', { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(1500)
await page.evaluate(() => localStorage.setItem('open-collections:intro-seen:v1', '1'))
await page.reload({ waitUntil: 'domcontentloaded' })
await page.fill('input[type="search"], .searchbar input', 'cat portrait')
await page.keyboard.press('Enter')
await page.waitForSelector('.card img.loaded', { timeout: 40000 })
await page.click('.card >> nth=0')
await page.waitForSelector('.viewer', { timeout: 20000 })
console.log('1. viewer opens on mobile:', await page.locator('.viewer').count())
await page.click('button:has-text("Edit")')
await page.waitForTimeout(4000)
console.log('2. editor mounted:', await page.locator('.editor').count())
const stage = await page.locator('.editor .stage canvas').boundingBox().catch(() => null)
const vp = page.viewportSize()
console.log('   preview canvas:', stage ? `${Math.round(stage.width)}x${Math.round(stage.height)} at y=${Math.round(stage.y)}` : 'MISSING')
console.log('   canvas within viewport:', stage ? (stage.y >= 0 && stage.y + stage.height <= vp.height + 2 ? 'yes' : `NO (bottom ${Math.round(stage.y + stage.height)} vs ${vp.height})`) : 'n/a')
// can an effect be applied?
const chip = page.getByRole('button', { name: 'Halftone', exact: true })
console.log('3. halftone chip visible:', await chip.isVisible().catch(() => false))
await chip.click()
await page.waitForTimeout(3500)
const drew = await page.evaluate(() => { const c = document.querySelector('.editor .stage canvas'); if (!c) return 'no canvas'; const d = c.getContext('2d').getImageData(0, 0, Math.min(60, c.width), Math.min(60, c.height)).data; let n = 0; for (let i = 0; i < d.length; i += 4) if (d[i] < 200) n++; return `${c.width}x${c.height}, dark px in sample: ${n}` })
console.log('   after halftone:', drew)
// export row reachable?
const bar = await page.locator('.export-actions').boundingBox().catch(() => null)
console.log('4. export row:', bar ? `y=${Math.round(bar.y)} h=${Math.round(bar.height)} (viewport ${vp.height})` : 'MISSING', bar && bar.y + bar.height <= vp.height + 2 ? 'ON SCREEN' : 'OFF SCREEN')
const btns = await page.$$eval('.export-actions button', (b) => b.map((x) => `${x.textContent.trim()}${x.disabled ? '(disabled)' : ''}`))
console.log('   buttons:', btns.join(', '))
await page.screenshot({ path: 'data/shots/mobile-editor-check.png' })
console.log('5. page errors:', errs.length ? errs.slice(0, 4).join(' | ') : 'none')
await browser.close()
