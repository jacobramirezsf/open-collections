import { chromium, devices } from 'playwright'
const browser = await chromium.launch()
const page = await browser.newPage({ ...devices['iPhone 13'] })
page.on('pageerror', (e) => console.log('PAGEERROR:', e.message))
await page.goto('http://localhost:5180/', { waitUntil: 'domcontentloaded' })
await page.fill('input[type="search"], .searchbar input', 'tulip painting')
await page.keyboard.press('Enter')
await page.waitForSelector('.card img.loaded', { timeout: 30000 })
await page.click('.card >> nth=0')
await page.waitForSelector('.viewer', { timeout: 15000 })
await page.click('button:has-text("Edit")')
await page.waitForTimeout(2500)
const vh = page.viewportSize().height
const bar = await page.locator('.export-actions').boundingBox()
console.log('viewport h', vh, '| export row visible at y', bar?.y.toFixed(0), 'h', bar?.height.toFixed(0), '=>', bar && bar.y + bar.height <= vh + 1 ? 'ON SCREEN' : 'OFF SCREEN')
const opts = await page.$$eval('.ctl.row select option', (os) => os.map((o) => o.textContent))
console.log('background options:', opts.length, opts.slice(0, 4).join(' / '))
console.log('color input shown:', await page.locator('input[aria-label="Background color"]').count())
await page.screenshot({ path: 'data/shots/dock-bg.png' })
// pick a fabric sheet -> color input hides, sheet mode appears
await page.selectOption('.ctl.row select', 'img:denim')
await page.waitForTimeout(1500)
console.log('after sheet — color input:', await page.locator('input[aria-label="Background color"]').count(), '| sheet mode:', await page.locator('.seg button:has-text("overlay")').count())
const bar2 = await page.locator('.export-actions').boundingBox()
console.log('export row still on screen:', bar2 && bar2.y + bar2.height <= vh + 1)
await page.screenshot({ path: 'data/shots/dock-sheet.png' })
await browser.close()
