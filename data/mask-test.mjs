import { chromium, devices } from 'playwright'
const browser = await chromium.launch()
const page = await browser.newPage({ ...devices['iPhone 13'] })
page.on('pageerror', (e) => console.log('PAGEERROR:', e.message))
await page.goto('http://localhost:5180/', { waitUntil: 'domcontentloaded' })
await page.fill('input[type="search"], .searchbar input', 'tulip painting')
await page.keyboard.press('Enter')
await page.waitForSelector('.card img.loaded', { timeout: 30000 })
await page.click('.card >> nth=0')
await page.waitForSelector('.viewer', { timeout: 15000 })
await page.click('button:has-text("Edit")')
await page.waitForTimeout(2500)
await page.click('button.mobile-only:has-text("Erase")')
await page.waitForSelector('.mask-tool', { timeout: 8000 })
await page.waitForTimeout(800)
// paint an erase stroke across the middle
const st = await page.locator('.mask-stage').boundingBox()
const y = st.y + st.height / 2
await page.mouse.move(st.x + 60, y)
await page.mouse.down()
for (let x = 60; x < st.width - 60; x += 12) await page.mouse.move(st.x + x, y + Math.sin(x / 30) * 24)
await page.mouse.up()
await page.waitForTimeout(400)
// restore part of it
await page.click('.seg button:has-text("Restore")')
await page.mouse.move(st.x + st.width / 2, y)
await page.mouse.down()
for (let x = st.width / 2; x < st.width / 2 + 90; x += 10) await page.mouse.move(st.x + x, y)
await page.mouse.up()
await page.waitForTimeout(400)
await page.screenshot({ path: 'data/shots/mask-tool.png' })
// undo count + apply
console.log('undo enabled:', await page.locator('.mask-tool button[aria-label="Undo"]:not([disabled])').count())
await page.click('button:has-text("Apply")')
await page.waitForTimeout(1500)
console.log('back in editor, cutout marker:', await page.locator('button:has-text("Background removed")').count())
await page.screenshot({ path: 'data/shots/mask-applied.png' })
await browser.close()
