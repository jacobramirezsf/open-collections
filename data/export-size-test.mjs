import { chromium, devices } from 'playwright'
const browser = await chromium.launch()
const page = await browser.newPage({ ...devices['iPhone 13'] })
page.on('pageerror', (e) => console.log('PAGEERROR:', e.message))
await page.goto('https://open-collections.com/', { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(1500)
await page.evaluate(() => localStorage.setItem('open-collections:intro-seen:v1', '1'))
await page.reload({ waitUntil: 'domcontentloaded' })
await page.fill('input[type="search"], .searchbar input', 'tulip painting')
await page.keyboard.press('Enter')
await page.waitForSelector('.card img.loaded', { timeout: 30000 })
await page.click('.card >> nth=0')
await page.waitForSelector('.viewer', { timeout: 15000 })
await page.click('button:has-text("Edit")')
await page.waitForTimeout(3000)
const sizeSel = await page.locator('.editor select').last().inputValue().catch(() => '?')
console.log('default export size value:', sizeSel)
// measure what the current canvas would produce as PNG vs JPEG
const r = await page.evaluate(async () => {
  const c = document.querySelector('.editor .stage canvas')
  const off = document.createElement('canvas')
  off.width = 3000; off.height = Math.round(3000 * c.height / c.width)
  off.getContext('2d').drawImage(c, 0, 0, off.width, off.height)
  const png = await new Promise((r) => off.toBlob(r, 'image/png'))
  const jpg = await new Promise((r) => off.toBlob(r, 'image/jpeg', 0.92))
  return { dims: `${off.width}x${off.height}`, png: png.size, jpg: jpg.size }
})
console.log(`at ${r.dims}: PNG ${(r.png/1e6).toFixed(1)} MB | JPEG ${(r.jpg/1e6).toFixed(1)} MB`)
await browser.close()
