import { chromium, devices } from 'playwright'
const browser = await chromium.launch()
const page = await browser.newPage({ ...devices['iPhone 13'] })
page.on('pageerror', (e) => console.log('PAGEERROR:', e.message))
await page.goto('http://localhost:5180/', { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(1200)
await page.evaluate(() => localStorage.setItem('open-collections:intro-seen:v1', '1'))
await page.reload({ waitUntil: 'domcontentloaded' })
await page.waitForTimeout(1200)
await page.click('button:has-text("Canvas")')
await page.waitForSelector('.canvas-studio')
for (const shape of ['arch', 'valley', 'circle', 'stack']) {
  await page.click('button:has-text("+ Add text")')
  await page.waitForSelector('.text-pop')
  await page.fill('.text-pop textarea', 'OPEN COLLECTIONS')
  await page.selectOption('.text-pop select >> nth=0', { label: 'Anton' })
  await page.selectOption('.text-pop select:has(option[value="circle"])', shape)
  await page.waitForTimeout(300)
  await page.click('.text-pop button:has-text("Add to canvas")')
  await page.waitForTimeout(2500)
  const d = await page.locator('.piece img').last().evaluate((el) => `${el.naturalWidth}x${el.naturalHeight}`)
  console.log(shape, '->', d)
  await page.screenshot({ path: `data/shots/text-${shape}.png` })
  // remove it before the next one
  await page.click('.piece >> nth=-1')
  await page.waitForTimeout(300)
  await page.click('button:has-text("Remove")')
  await page.waitForTimeout(400)
}
await browser.close()
