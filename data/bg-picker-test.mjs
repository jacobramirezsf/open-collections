import { chromium, devices } from 'playwright'
const browser = await chromium.launch()
const page = await browser.newPage({ ...devices['iPhone 13'] })
page.on('pageerror', (e) => console.log('PAGEERROR:', e.message))
await page.goto('http://localhost:5180/', { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(1200)
await page.evaluate(() => localStorage.setItem('open-collections:intro-seen:v1', '1'))
await page.reload({ waitUntil: 'domcontentloaded' })
await page.fill('input[type="search"], .searchbar input', 'tulip painting')
await page.keyboard.press('Enter')
await page.waitForSelector('.card img.loaded', { timeout: 30000 })
await page.click('.card >> nth=0')
await page.waitForSelector('.viewer', { timeout: 15000 })
await page.click('button:has-text("Edit")')
await page.waitForTimeout(2500)
await page.getByRole('button', { name: 'Halftone', exact: true }).click()
await page.waitForTimeout(2000)
// open picker
await page.click('.ctl.row button:has-text("Colour"), .ctl.row button')
await page.waitForSelector('.bg-pop', { timeout: 5000 })
console.log('1. picker sections:', await page.$$eval('.bg-pop .picker-h', (h) => h.map((x) => x.textContent).join(' / ')))
console.log('   tiles:', await page.locator('.bg-tile').count())
await page.screenshot({ path: 'data/shots/bg-picker.png' })
// pick a deckle sheet
await page.click('.bg-tile[title="Deckle white"]')
await page.waitForTimeout(2500)
const before = await page.evaluate(() => { const c = document.querySelector('.editor .stage canvas'); return { w: c.width, h: c.height } })
console.log('2. deckle applied:', before, before.w > before.h ? '(wide)' : '(tall)')
await page.screenshot({ path: 'data/shots/bg-deckle-0.png' })
// rotate 90
await page.click('.ctl.row button:has-text("Rotate")')
await page.waitForTimeout(2500)
const after = await page.evaluate(() => { const c = document.querySelector('.editor .stage canvas'); return { w: c.width, h: c.height } })
console.log('3. after rotate:', after, after.h > after.w ? 'PASS (now tall)' : 'FAIL')
await page.screenshot({ path: 'data/shots/bg-deckle-90.png' })
// garment submenu
await page.click('.ctl.row button >> nth=0')
await page.waitForSelector('.bg-pop')
await page.click('.bg-tile:has-text("Heavyweight hoodie")')
await page.waitForTimeout(600)
const colors = await page.locator('.bg-sub .bg-tile').count()
console.log('4. hoodie colours in submenu:', colors)
await page.screenshot({ path: 'data/shots/bg-garment-sub.png' })
await page.click('.bg-sub .bg-tile >> nth=2')
await page.waitForTimeout(3000)
console.log('5. garment applied, label:', (await page.locator('.ctl.row button').first().textContent()).trim())
await page.screenshot({ path: 'data/shots/bg-garment.png' })
await browser.close()
