import { chromium } from 'playwright'
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
page.on('pageerror', (e) => console.log('PAGEERROR:', e.message))
await page.goto('http://localhost:5180/', { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(1200)
await page.evaluate(() => localStorage.setItem('open-collections:intro-seen:v1', '1'))
await page.reload({ waitUntil: 'domcontentloaded' })
await page.waitForTimeout(1200)
await page.click('button:has-text("Canvas")')
await page.waitForSelector('.canvas-studio')
await page.evaluate(() => {
  const mk = (c) => { const cv = document.createElement('canvas'); cv.width = 240; cv.height = 180
    const x = cv.getContext('2d'); x.fillStyle = c; x.fillRect(0, 0, 240, 180); return cv.toDataURL() }
  const docs = JSON.parse(localStorage.getItem('open-collections:canvases:v1'))
  docs[0].pieces = [{ id: 'a', src: mk('#c33'), x: 500, y: 600, scale: .5, rotation: 0, w: 240, h: 180, title: 'red' }]
  localStorage.setItem('open-collections:canvases:v1', JSON.stringify(docs)); location.reload()
})
await page.waitForTimeout(1500)
const dock = await page.locator('.canvas-dock').boundingBox()
const stage = await page.locator('.canvas-stage').boundingBox()
console.log('1. desktop layout — sidebar', Math.round(dock.width), 'x', Math.round(dock.height), '| stage', Math.round(stage.width), 'x', Math.round(stage.height))
console.log('   sidebar is a left rail:', dock.x < 300 && dock.height > 500 ? 'PASS' : 'FAIL')
await page.click('.piece')
await page.waitForTimeout(400)
console.log('2. corner handles:', await page.locator('.scale-handle').count(), '| rotate handle:', await page.locator('.rotate-handle').count())
// rotate by dragging the grip
const rot = await page.locator('.rotate-handle').boundingBox()
const pc = await page.locator('.piece').boundingBox()
await page.mouse.move(rot.x + rot.width / 2, rot.y + rot.height / 2)
await page.mouse.down(); await page.mouse.move(pc.x + pc.width + 60, pc.y + pc.height / 2, { steps: 10 }); await page.mouse.up()
await page.waitForTimeout(500)
const deg = await page.evaluate(() => JSON.parse(localStorage.getItem('open-collections:canvases:v1'))[0].pieces[0].rotation)
console.log('3. rotate handle:', Math.round(deg), 'deg', Math.abs(deg) > 5 ? 'PASS' : 'FAIL')
// scale from the top-left corner
const before = await page.evaluate(() => JSON.parse(localStorage.getItem('open-collections:canvases:v1'))[0].pieces[0].scale)
const nw = await page.locator('.scale-handle.nw').boundingBox()
await page.mouse.move(nw.x + 12, nw.y + 12)
await page.mouse.down(); await page.mouse.move(nw.x - 70, nw.y - 70, { steps: 10 }); await page.mouse.up()
await page.waitForTimeout(500)
const after = await page.evaluate(() => JSON.parse(localStorage.getItem('open-collections:canvases:v1'))[0].pieces[0].scale)
console.log('4. NW corner resize:', before.toFixed(2), '->', after.toFixed(2), after > before ? 'PASS' : 'FAIL')
// artboard zoom
await page.click('.zoombar button:has-text("+")')
await page.click('.zoombar button:has-text("+")')
await page.waitForTimeout(500)
console.log('5. zoom control:', await page.locator('.zoomlabel').textContent())
await page.screenshot({ path: 'data/shots/canvas-desktop-new.png' })
await browser.close()
